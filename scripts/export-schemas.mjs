import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import path from "node:path";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const formsDir = path.join(__dirname, "..", "src", "forms");
const outFile = path.join(__dirname, "..", "apps-script", "Forms.gs");

const META_SUFFIX = ".meta.json";
const readJson = (file) => JSON.parse(readFileSync(path.join(formsDir, file), "utf8"));
const files = readdirSync(formsDir).filter((f) => f.endsWith(".json"));

const forms = {};
for (const file of files.filter((f) => !f.endsWith(META_SUFFIX))) {
  const def = readJson(file);
  forms[def.id] = def;
}

// `<id>.meta.json` holds analysis-only item metadata. It reaches the backend (for the long-format tab)
// but is never bundled into the front end, so participants cannot see it.
for (const file of files.filter((f) => f.endsWith(META_SUFFIX))) {
  const meta = readJson(file);
  const form = forms[meta.formId];
  if (!form) throw new Error(`${file}: no form with id "${meta.formId}"`);
  form.itemMeta = { round: meta.round, itemVersion: meta.itemVersion, items: meta.items };
}

const banner = "// GENERATED by scripts/export-schemas.mjs from src/forms/*.json. Do not edit by hand.\n";
const content = `${banner}const FORMS = ${JSON.stringify(forms, null, 2)};\n`;

writeFileSync(outFile, content, "utf8");
console.log(`Wrote ${outFile} with forms: ${Object.keys(forms).join(", ")}`);
